--Crear la base de datos
CREATE DATABASE bd_laboratorio_orm;

--crear esquema
CREATE SCHEMA IF NOT EXISTS catalogos;

--crear la tabla tipo_equipo
CREATE TABLE catalogos.tipo_equipo(
	id_tipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nombre VARCHAR(100) NOT NULL UNIQUE,
	descripcion VARCHAR(250)
);

--Crear la tabla equipo
CREATE TABLE catalogos.equipo(
	id_equipo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	codigo VARCHAR(10) UNIQUE NOT NULL,
	nombre VARCHAR(100) NOT NULL,
	marca VARCHAR(50) NOT NULL,
	estado VARCHAR(30) NOT NULL,
	cantidad INT NOT NULL,
	id_tipo BIGINT NOT NULL,

	CONSTRAINT validar_cantidad
	   CHECK(cantidad >=0),
	CONSTRAINT validar_estado
	   CHECK(estado IN (
             'Disponible',
			 'En Mantenimiento',
			 'Fuera de servicio'
	   )),
	CONSTRAINT fk_equipo_tipo 
		FOREIGN KEY(id_tipo)
		REFERENCES catalogos.tipo_equipo(id_tipo)
		
		
);
